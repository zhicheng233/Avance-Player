    private string _cultureName;

    public LocalizedText() {
        _cultureName = CultureInfo.CurrentUICulture.Name.StartsWith("zh", StringComparison.OrdinalIgnoreCase)
            ? "zh-CN"
            : "en-US";
    }

    public event PropertyChangedEventHandler? PropertyChanged;

    public string this[string key] {
        get {
            var current = _cultureName == "zh-CN" ? Chinese : English;
            if (current.TryGetValue(key, out var value)) return value;
            return English.TryGetValue(key, out value) ? value : $"[{key}]";
        }
    }

    public string LanguageName => _cultureName == "zh-CN" ? "EN" : "中文";
    public string CultureName => _cultureName;

    public void ToggleLanguage() => SetCulture(_cultureName == "zh-CN" ? "en-US" : "zh-CN");

    private void SetCulture(string cultureName) {
        if (_cultureName == cultureName) return;
        _cultureName = cultureName;
        CultureInfo.CurrentCulture = CultureInfo.GetCultureInfo(cultureName);
        CultureInfo.CurrentUICulture = CultureInfo.GetCultureInfo(cultureName);
        // Avalonia's indexer bindings listen for "Item"; WPF-style consumers and the view model
        // also react to "Item[]", so raise both when the language changes.
        OnPropertyChanged("Item");
        OnPropertyChanged("Item[]");
        OnPropertyChanged(nameof(LanguageName));
        OnPropertyChanged(nameof(CultureName));
    }

    public string Format(string key, params object[] values) =>
        string.Format(CultureInfo.GetCultureInfo(_cultureName), this[key], values);

    private void OnPropertyChanged([CallerMemberName] string? propertyName = null) =>
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
